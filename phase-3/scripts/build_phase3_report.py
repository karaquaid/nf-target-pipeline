#!/usr/bin/env python3
"""Phase 3, step 7: generate phase-3/docs/phase3-expression-targets.md.

Every current-state number in the write-up is recomputed from the committed
tables, so the document cannot drift from the data. Process counts that no
longer exist in any table (what a step started with, what an earlier round
dropped) live in PROCESS_HISTORY with the commit that established them, the same
arrangement the Phase 1b report uses.

The generated text must not contain an em dash; project style forbids it, and
this script enforces that at build time rather than trusting review.

Usage, from the repository root, and the order the Phase 3 scripts run in:

    python phase-3/scripts/phase3_contrast_labels.py --ranked-dir <dir>
    python phase-3/scripts/phase3_rank_matrix.py --ranked-dir <dir> --build-dir <build>
    Rscript  phase-3/scripts/phase3_aggregate.R <build>
    python phase-3/scripts/phase3_kegg_fetch.py
    python phase-3/scripts/phase3_candidates.py --build-dir <build>
    python phase-3/scripts/phase3_kegg_enrich.py --build-dir <build>
    python phase-3/scripts/phase3_figure.py
    python phase-3/scripts/build_phase3_report.py      # this script
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

# Counts from the Phase 2 handover and from steps whose inputs are not committed.
# Each is stated with where it came from so it can be rechecked.
PROCESS_HISTORY = {
    "phase2_manifest_rows": (20, "phase-2/data/phase2-ingestion-manifest.csv at commit 4dd91fa"),
    "phase2_ranked_datasets": (15, "manifest rows with pipeline_role == ranked"),
    "phase2_unranked_datasets": (5, "manifest rows with pipeline_role == ingested_no_ranking"),
    "phase2_unproduced": ("GSE292071", "named in the Phase 2 section of docs/project-plan.md as the "
                                       "one ranked-set dataset with no ranked list"),
}

PRETTY = {
    "nf1_mpnst_vs_benign_pnst": "NF1, MPNST against a benign nerve sheath arm",
    "nf1_atypical_vs_benign_pnst": "NF1, atypical neurofibroma against a benign arm",
    "nf1_benign_subtype_vs_pnf": "NF1, benign neurofibroma subtype against plexiform neurofibroma",
    "nf1_pnst_vs_normal": "NF1, nerve sheath tumour against normal nerve",
    "nf1_bone_vs_normal": "NF1, bone lesion against unaffected bone",
    "nf1_glioma_vs_normal_brain": "NF1, glioma against non-neoplastic brain",
    "nf2swn_schwannoma_vs_normal": "NF2-SWN, schwannoma against normal nerve",
    "nf2swn_painful_vs_non_painful_schwannoma": "NF2-SWN, painful against non-painful schwannoma",
}
TIERS = ["A_aggregated", "B_replicated", "C_single_dataset"]


def table(rows: list[list[str]], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(repo: Path) -> str:
    d = repo / "phase-3/data"
    labels = pd.read_csv(d / "phase3-contrast-labels.csv")
    rank_in = pd.read_csv(d / "phase3-rank-input-summary.csv")
    full = pd.read_csv(d / "phase3-expression-targets.csv.gz")
    cand = pd.read_csv(d / "phase3-candidate-targets.csv")
    enr = pd.read_csv(d / "phase3-kegg-enrichment.csv")
    kegg = pd.read_csv(d / "phase3-kegg-gene-pathway.tsv.gz", sep="\t")
    prov = json.loads((d / "phase3-kegg-provenance.json").read_text())

    usable = labels[labels.usable_for_candidates]
    n_contrasts, n_datasets = len(labels), labels.accession.nunique()
    n_strata = usable.comparison_class.nunique()
    tiers = full.groupby("evidence_tier").size().reindex(TIERS, fill_value=0)
    sig_paths = enr[enr.fdr < 0.05]

    L = []
    A = L.append
    A("# Phase 3: Candidate Target Identification from Expression Data\n")
    A("Generated by `phase-3/scripts/build_phase3_report.py`. Every current-state number below "
      "is recomputed from the committed Phase 3 tables at build time.\n")

    A("## Purpose\n")
    A(f"Phase 2 left {PROCESS_HISTORY['phase2_ranked_datasets'][0]} datasets with a ranked "
      f"differential-expression list. Phase 3 turns those rankings into an expression-derived "
      f"candidate target list, labelled by disease and manifestation, that Phase 3b can set beside "
      f"the literature-derived list from Phase 1b.\n")
    A(f"The launch set spans 28 platforms and most contrasts compare two disease states rather than "
      f"tumour against normal, so effect sizes are not comparable on a common scale. Phase 3 "
      f"therefore combines datasets by rank, within strata that never mix a disease-vs-normal "
      f"reading with a between-state one. The {n_contrasts} contrasts across {n_datasets} datasets "
      f"fall into {labels.comparison_class.nunique()} such strata, {n_strata} of which carry a "
      f"contrast usable for candidate generation.\n")

    A("## The eight build steps, in order\n")
    A("1. `phase3_contrast_labels.py` reads the Phase 2 ranked lists, finds every contrast they "
      "carry, and labels each one with disease, manifestation(s) and its aggregation stratum. "
      "Disease and manifestation are taken from the Phase 1a dataset-level labels and narrowed to "
      "the arms the contrast actually compares; the script fails if a narrowed manifestation is not "
      "among the ones Phase 1a recorded for that dataset, or if a stratum would mix effect types.\n")
    A("2. `phase3_rank_matrix.py` converts each ranked list into direction-aware normalized ranks "
      "over that contrast's own measured symbol set, collapses probes to symbols by largest "
      "absolute test statistic, and averages a dataset's several contrasts within a stratum into "
      "one dataset-level ranking so no dataset enters aggregation more than once.\n")
    A("3. `phase3_aggregate.R` runs Robust Rank Aggregation per stratum and direction over the "
      "gene-by-dataset rank matrix, with unmeasured genes passed in as missing.\n")
    A("4. `phase3_kegg_fetch.py` builds the human symbol-to-pathway map from the KEGG REST API.\n")
    A("5. `phase3_candidates.py` assigns each gene an evidence tier, labels it by disease and "
      "manifestation from the datasets that support it, flags the germline NF disease genes, and "
      "writes the full table and the filtered candidate deliverable.\n")
    A("6. `phase3_kegg_enrich.py` tests KEGG pathway over-representation per stratum and direction "
      "against that stratum's own measured background.\n")
    A("7. `phase3_figure.py` draws Figure 1.\n")
    A("8. `build_phase3_report.py` writes this document.\n")

    A("## Current outputs\n")
    outs = [
        ["`phase-3/data/phase3-contrast-labels.csv`", f"{len(labels)} contrasts",
         "one row per Phase 2 contrast with disease, manifestation(s), stratum, arms and the basis for each label"],
        ["`phase-3/data/phase3-rank-input-summary.csv`", f"{len(rank_in)} contrasts",
         "what entered the ranking per contrast and what was dropped as unmapped or collapsed to a symbol"],
        ["`phase-3/data/phase3-expression-targets.csv.gz`", f"{len(full):,} rows",
         "full table: every gene with expression evidence in a stratum, with its tier and statistics"],
        ["`phase-3/data/phase3-candidate-targets.csv`", f"{len(cand):,} rows",
         "the filtered deliverable Phase 3b consumes"],
        ["`phase-3/data/phase3-kegg-enrichment.csv`", f"{len(enr):,} tests",
         "KEGG over-representation per stratum and direction"],
        ["`phase-3/data/phase3-kegg-gene-pathway.tsv.gz`", f"{len(kegg):,} links",
         "symbol to human pathway map the enrichment reads"],
        ["`phase-3/data/phase3-kegg-provenance.json`", "1 record",
         "KEGG endpoints, pathway database stamp and fetch date"],
        ["`phase-3/docs/figures/phase3-expression-evidence.png`", "1 figure",
         "Figure 1, candidates by evidence tier and the pathways they fall in"],
    ]
    A(table(outs, ["File", "Size", "What it holds"]) + "\n")

    A("## Figure 1\n")
    A("![Candidates per stratum by evidence tier, and the KEGG pathways they fall in]"
      "(figures/phase3-expression-evidence.png)\n")
    A(f"Panel a: candidate rows per stratum, coloured by the strongest support each candidate has, "
      f"with the number of datasets in the stratum in brackets. Panel b: the KEGG pathways reaching "
      f"FDR below 0.05, at most four per stratum and direction, marker area proportional to the "
      f"number of candidates annotated to the pathway. Counts are gene-by-direction rows, so a gene "
      f"can appear in more than one stratum. n is the number of datasets shown per bar; the unit of "
      f"replication throughout Phase 3 is the dataset, never the sample.\n")

    A("## How a gene becomes a candidate\n")
    A("Three evidence tiers, recorded per gene per stratum per direction rather than collapsed into "
      "one significance call, because the strata differ so much in how many datasets they have:\n")
    A(f"* **A_aggregated** ({tiers['A_aggregated']} rows). Robust Rank Aggregation rho passes "
      f"FDR below 0.05 within the stratum, and at least two datasets measured the gene. The second "
      f"condition matters: a gene only one dataset measured still receives an RRA score, computed "
      f"from a single normalized rank, and a top rank in one deep list can pass FDR on its own, "
      f"which is not an aggregated call.\n")
    A(f"* **B_replicated** ({tiers['B_replicated']} rows). Significant in its own dataset's "
      f"differential expression at FDR below 0.05 in two or more datasets of the stratum, in the "
      f"same direction, with no dataset of the stratum significant in the opposite direction.\n")
    A(f"* **C_single_dataset** ({tiers['C_single_dataset']} rows). Significant in exactly one "
      f"dataset of the stratum. This is every gene from the single-dataset strata, and genes in "
      f"multi-dataset strata that only one dataset supports.\n")
    A("Rank aggregation can call a gene that no single dataset calls, which is the point of running "
      "it: consistently high ranks across many datasets without clearing FDR anywhere. Those genes "
      f"are kept. In the current tables {int(((full.evidence_tier == 'A_aggregated') & (full.n_datasets_significant == 0)).sum())} "
      f"rows are aggregation calls with no single-dataset call behind them "
      f"({', '.join(sorted(full.loc[(full.evidence_tier == 'A_aggregated') & (full.n_datasets_significant == 0), 'gene_symbol']))}).\n")

    A("## Evidence by stratum\n")
    rows = []
    for cls in sorted(usable.comparison_class.unique()):
        g = full[full.comparison_class == cls]
        c = cand[cand.comparison_class == cls]
        lab = usable[usable.comparison_class == cls]
        t = g.groupby("evidence_tier").size().reindex(TIERS, fill_value=0)
        n_sig = int((enr[(enr.comparison_class == cls) & (enr.fdr < 0.05)]).shape[0])
        rows.append([PRETTY[cls], lab.accession.nunique(), len(lab),
                     lab.effect_type.iloc[0].replace("_", " "),
                     t["A_aggregated"], t["B_replicated"], t["C_single_dataset"],
                     len(c), n_sig])
    A(table(rows, ["Stratum", "Datasets", "Contrasts", "Effect type", "Tier A", "Tier B",
                   "Tier C", "Candidates", "KEGG pathways at FDR < 0.05"]) + "\n")

    A("## Evidence by disease and manifestation\n")
    A("Counts of distinct candidate genes. A gene labelled with several manifestations is counted "
      "under each, and the same gene can appear in more than one disease, so the rows do not sum to "
      "the table length.\n")
    rows = []
    exploded = (cand.assign(man=cand.manifestations.str.split("|"))
                    .explode("man").assign(dis=lambda x: x.disease.str.split("|")).explode("dis"))
    for (dis, man), g in exploded.groupby(["dis", "man"]):
        rows.append([dis, man, g.gene_symbol.nunique(),
                     g[g.evidence_tier != "C_single_dataset"].gene_symbol.nunique(),
                     g.comparison_class.nunique()])
    rows.sort(key=lambda r: (r[0], -r[2]))
    A(table(rows, ["Disease", "Manifestation", "Candidate genes",
                   "With cross-dataset support", "Strata"]) + "\n")
    A("SWN, schwannomatosis without an NF2 germline variant, has no dataset in the Phase 2 launch "
      "set and therefore no expression-derived candidate. That is an explicit zero for Phase 3b, "
      "not an omission.\n")

    A("## Top candidates\n")
    A("The five strongest candidates per stratum and direction, by the stratum's priority "
      "statistic. Fold changes are from the supporting dataset with the smallest FDR and are not "
      "comparable between strata.\n")
    rows = []
    for cls in sorted(cand.comparison_class.unique()):
        for direction in ("up", "down"):
            g = cand[(cand.comparison_class == cls) & (cand.direction == direction)].head(5)
            if g.empty:
                continue
            rows.append([PRETTY[cls], "higher in test arm" if direction == "up" else "lower in test arm",
                         ", ".join(g.gene_symbol), g.evidence_tier.iloc[0]])
    A(table(rows, ["Stratum", "Direction", "Top five", "Tier of the first"]) + "\n")

    A("## Pathway enrichment\n")
    A(f"KEGG pathway database stamp `{prov['kegg_pathway_db_info']}`, fetched {prov['fetched']} from "
      f"`{prov['endpoints']['gene_pathway']}` and the three sibling endpoints listed in "
      f"`phase3-kegg-provenance.json`. Endpoint syntax was checked against "
      f"{prov['documentation_verified_against']} before the query code was written. The map covers "
      f"{prov['distinct_symbols']:,} symbols over {prov['distinct_pathways']} human pathways.\n")
    A("Earlier phases mapped pathways for target names chosen by hand. This step runs the other "
      "way, from each stratum's whole measured symbol set to the pathways its candidates fall in, "
      "which is what the plan means by extending the KEGG step to work from expression data. The "
      "background is the stratum's own measured symbols intersected with the pathway-annotated "
      "genes, not all of KEGG: using all of KEGG would score a pathway as enriched merely because "
      "the stratum's platforms covered it well, which is how a targeted panel manufactures "
      "enrichment. GSE239561's 770-gene panel is itself pathway-selected, so this matters most for "
      "the two strata it contributes to.\n")
    A(f"{len(sig_paths)} pathway tests reach FDR below 0.05. The pattern per stratum:\n")
    for cls in sorted(sig_paths.comparison_class.unique()):
        for direction in ("up", "down"):
            g = sig_paths[(sig_paths.comparison_class == cls) & (sig_paths.direction == direction)]
            if g.empty:
                continue
            names = g.sort_values("fdr").pathway_name.str.replace(
                " - Homo sapiens (human)", "", regex=False).head(4)
            A(f"* {PRETTY[cls]}, {'higher' if direction == 'up' else 'lower'} in the test arm: "
              f"{', '.join(names)}. Strongest FDR {g.fdr.min():.2g}.\n")

    A("## Scope decisions\n")
    A("* **Germline NF disease genes are flagged out of the candidate list.** NF1, NF2, SMARCB1, "
      f"LZTR1 and SPRED1, the same gene set and the same reason as Phase 1b: their role is "
      f"established and re-prioritising them tells the project nothing. "
      f"{int(full.driver_gene.sum())} rows carry `driver_gene = True` in the full table and are "
      f"absent from the candidate file. The flag is a column, never a deletion, so the decision is "
      f"reversible by changing one filter.\n")
    A(f"* **Two contrasts contribute no candidates.** "
      f"{', '.join(labels.loc[~labels.usable_for_candidates, 'accession'] + ' ' + labels.loc[~labels.usable_for_candidates, 'contrast'])}. "
      f"Both are kept in the contrast table with the reason in the `basis` column. The first "
      f"compares a treated arm against the control arm, so it reads drug response rather than "
      f"disease state; the second has a single sample in its test arm.\n")
    A("* **Fold change is not thresholded.** The launch set's log2 fold changes come from limma, "
      "DESeq2, two-colour limma, NanoString housekeeping limma and pseudobulk limma across 28 "
      "platforms, and are not on a common scale, which is the reason this phase ranks rather than "
      "pools. A shared fold-change cutoff would be stricter for some engines than others. "
      "Per-dataset fold changes are reported in the tables for reference and should not be compared "
      "between strata.\n")
    A("* **A prioritisation cap of 200 genes per stratum per direction** keeps the candidate "
      "deliverable comparable between strata, so one deeply sequenced single dataset cannot "
      "dominate the Phase 3b coverage picture against a replicated stratum. The full table carries "
      "every gene with evidence; the cap is one argument to `phase3_candidates.py`.\n")

    A("## Limitations\n")
    tier_a_by_cls = (full[full.evidence_tier == "A_aggregated"].groupby("comparison_class").size()
                         .reindex(sorted(usable.comparison_class.unique()), fill_value=0))
    no_tier_a = int((tier_a_by_cls == 0).sum())
    multi = [c for c in tier_a_by_cls.index
             if usable[usable.comparison_class == c].accession.nunique() >= 2]
    singles = sorted(c for c in tier_a_by_cls.index
                     if usable[usable.comparison_class == c].accession.nunique() == 1)
    A(f"* **Most strata have two datasets, and Robust Rank Aggregation has almost no power there.** "
      f"With two lists the best attainable rho is bounded by the product of two near-top ranks, and "
      f"after Benjamini-Hochberg across tens of thousands of genes it rarely clears 0.05. Tier A is "
      f"empty for {no_tier_a} of the {n_strata} strata, and for "
      f"{int((tier_a_by_cls[multi] == 0).sum())} of the {len(multi)} strata that have more than one "
      f"dataset at all. That is a statement about the launch set rather than about the biology; "
      f"tier B exists so those strata are not reported as evidence-free.\n")
    A(f"* **{len(singles)} strata rest on one dataset** and can show no replication at all: "
      f"{', '.join(PRETTY[c] for c in singles)}. Every gene from these strata carries "
      f"`unreplicated = True`, and the benign subtype comparison produced no significant gene in "
      f"its single contrast and so no candidate at all.\n")
    bone = full[full.comparison_class == "nf1_bone_vs_normal"]
    bone_ds = sorted(set(";".join(bone.supporting_datasets.fillna("")).split(";")) - {""})
    A(f"* **The two bone datasets have two samples per arm each.** Every one of the "
      f"{len(bone)} bone candidates is supported by {' and '.join(bone_ds)} alone, so the stratum's "
      f"evidence comes from one dataset despite the stratum having two.\n")
    A("* **GSE232516's reference arm is unaffected tissue from a different anatomical site** in the "
      "same patients, not a healthy donor. Its manifest effect type reads disease_vs_normal; what "
      "it measures is a between-site difference.\n")
    A("* **The painful-schwannoma stratum's strongest pathway is cornified envelope formation**, "
      "which is a skin signature rather than a nerve one and most likely reflects differing amounts "
      "of overlying tissue between the two arms. It is reported as found, not interpreted as "
      "biology.\n")
    A("* **Pseudobulk single-cell strata mix cell compositions.** GSE318927 and GSE232516 are "
      "pseudobulk profiles, so a candidate there can reflect a shift in which cells are present "
      "rather than a change within a cell type.\n")
    A(f"* **{PROCESS_HISTORY['phase2_unproduced'][0]} has no ranked list** and so contributes "
      f"nothing to Phase 3, and the {PROCESS_HISTORY['phase2_unranked_datasets'][0]} datasets Phase 2 "
      f"ingested without ranking are absent by construction.\n")

    A("## How to reproduce\n")
    A("From the repository root, with the Phase 2 ranked lists in `<ranked-dir>` and a scratch "
      "`<build-dir>`. The ranked lists are not committed; they are the Phase 2 artifact "
      "`phase2-ranked-lists.tar.gz`.\n")
    A("```sh\n"
      "python  phase-3/scripts/phase3_contrast_labels.py --ranked-dir <ranked-dir>\n"
      "python  phase-3/scripts/phase3_rank_matrix.py     --ranked-dir <ranked-dir> --build-dir <build-dir>\n"
      "Rscript phase-3/scripts/phase3_aggregate.R        <build-dir>\n"
      "python  phase-3/scripts/phase3_kegg_fetch.py\n"
      "python  phase-3/scripts/phase3_candidates.py      --build-dir <build-dir>\n"
      "python  phase-3/scripts/phase3_kegg_enrich.py     --build-dir <build-dir>\n"
      "python  phase-3/scripts/phase3_figure.py\n"
      "python  phase-3/scripts/build_phase3_report.py\n"
      "```\n")
    A("Python steps need pandas, numpy and scipy. The aggregation step needs R with "
      "RobustRankAggreg and data.table. `phase3_kegg_fetch.py` is the only step that touches the "
      "network; rerunning it refreshes the pathway map and its provenance stamp, and the KEGG REST "
      "service throttles repeat callers, so it retries on timeout rather than failing.\n")

    A("## Open items for Phase 3b\n")
    A("Phase 3b is a human decision point. What it now has from both sides:\n")
    A("* The literature-derived candidate list from Phase 1b, in `phase-1b/data/phase1b-candidate-targets.csv`.\n")
    A(f"* This expression-derived list, {cand.gene_symbol.nunique():,} distinct genes over "
      f"{cand.comparison_class.nunique()} strata, with each gene's support tiered so a manifestation "
      f"backed by one dataset is visibly different from one backed by seven.\n")
    A("* An explicit zero for SWN and for every manifestation of the fixed vocabulary that no "
      "dataset in the launch set speaks to.\n")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", default=".")
    args = ap.parse_args()
    repo = Path(args.repo)

    text = build(repo)
    if "\u2014" in text:
        raise AssertionError("em dash in generated text; project style forbids it")
    out = repo / "phase-3/docs/phase3-expression-targets.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text):,} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
